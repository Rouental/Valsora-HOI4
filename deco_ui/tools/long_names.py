"""Which country names need the smaller font under the flag (the top bar's medallion), as a scripted trigger.

    python long_names.py ["<Valsora mod folder>"]

Each name variant from the Valsora mod's English localisation (TAG, TAG_<ideology> and cosmetic tags) is
greedy-wrapped at the large name font's metrics (layout.NAME_FONTS, the generated .fnt files); a name with a
word wider than the box, or needing more than one line, is listed in valsora_deco_long_name, which switches the
medallion's name to the small cut (since v0.8.4: two lines of the large letters filled the box to the flag's frame,
"for long names like Kampf, they ride up against the flag", the user, 2026-10-16). Run by make_topbar.py, and by the Valsora build (scripts/deco_ui.py) so a new
country is caught at once. Without the mod's localisation the trigger is always true (small font everywhere).
"""
import os
import re
import sys

import layout as L
from paths import MOD as MOD_DIR, VALSORA as VALSORA_DIR

N = L.NAME


def name_fits(name, font, width, lines=2):
    words, used, cur = name.upper().split(), 0, 0
    space = L.measure(font, " ")
    for wd in words:
        w = L.measure(font, wd)
        if w > width:
            return False
        if cur and cur + space + w <= width:
            cur += space + w
        else:
            used += 1
            cur = w
    return used <= lines


def write(VALSORA=VALSORA_DIR, MOD=MOD_DIR):
    long_tags, long_cosmetic, have_data, clauses = set(), set(), False, []
    loc_dir = os.path.join(VALSORA, "localisation")
    if os.path.isdir(loc_dir):
        text = ""
        for root, _, files in os.walk(loc_dir):
            for f in sorted(files):
                if f.endswith("_l_english.yml") and not f.startswith("valsora_deco"):
                    text += open(os.path.join(root, f), encoding="utf-8-sig").read() + "\n"
        tags = set()
        for root, _, files in os.walk(os.path.join(VALSORA, "common", "country_tags")):
            for f in files:
                tags |= set(re.findall(r"^\s*([A-Z][A-Z0-9]{2})\s*=", open(os.path.join(root, f), encoding="utf-8-sig").read(), re.M))
        cosmetic = set()
        for root, _, files in os.walk(VALSORA):
            for f in files:
                if f.endswith(".txt"):
                    cosmetic |= set(re.findall(r"set_cosmetic_tag\s*=\s*([A-Za-z0-9_]+)",
                                               open(os.path.join(root, f), encoding="utf-8-sig", errors="ignore").read()))
        ideologies = ["democratic", "communism", "fascism", "neutrality"]
        ipath = os.path.join(VALSORA, "common", "ideologies")
        if os.path.isdir(ipath):
            found = []
            for f in sorted(os.listdir(ipath)):
                src_i = re.sub(r"#[^\n]*", "", open(os.path.join(ipath, f), encoding="utf-8-sig").read())
                depth = 0
                for m in re.finditer(r"([A-Za-z_]+)\s*=\s*\{|\{|\}", src_i):
                    if m.group(0).endswith("{") and m.group(1):
                        if depth == 1:
                            found.append(m.group(1))
                        depth += 1
                    elif m.group(0) == "{":
                        depth += 1
                    else:
                        depth -= 1
            ideologies = found or ideologies
        names = dict(re.findall(r'^\s*([A-Za-z0-9_]+):\d*\s+"(.*)"\s*$', text, re.M))
        for base in sorted(tags | cosmetic):
            test = f"has_cosmetic_tag = {base}" if base in cosmetic else f"tag = {base}"
            if base in names and not name_fits(names[base], L.NAME_FONTS[0], N["w"] - 2, lines=1):
                clauses.append(test)
                (long_cosmetic if base in cosmetic else long_tags).add(base)
                continue
            for ideo in ideologies:
                v = names.get(f"{base}_{ideo}")
                if v and not name_fits(v, L.NAME_FONTS[0], N["w"] - 2, lines=1):
                    clauses.append(f"AND = {{ {test} has_government = {ideo} }}")
                    (long_cosmetic if base in cosmetic else long_tags).add(f"{base}_{ideo}")
        have_data = bool(tags)
    os.makedirs(MOD + "common/scripted_triggers", exist_ok=True)
    if have_data:
        body = "\n".join(f"\t\t{c}" for c in clauses)
        trig = f"\tOR = {{\n{body}\n\t\talways = no\n\t}}"
    else:
        trig = "\talways = yes   # built without the Valsora mod's localisation: use the small font everywhere"
    open(MOD + "common/scripted_triggers/valsora_deco_triggers.txt", "w", encoding="utf-8", newline="\n").write(
        "# Valsora Deco UI - generated by tools/long_names.py from the Valsora mod's localisation.\n"
        "# True when the country's current name would not fit the large name font under the flag\n"
        "# (a word wider than the medallion, or more than two lines), so the smaller cut is shown.\n"
        f"valsora_deco_long_name = {{\n{trig}\n}}\n")
    return long_tags, long_cosmetic


if __name__ == "__main__":
    lt, lc = write(*(a if a.endswith(os.sep) else a + os.sep for a in sys.argv[1:2]))
    print("long names:", sorted(lt), sorted(lc))
