"""Build interface/musicplayer.gui (2026-10-19): the music player's window, every element and name kept (its other
pictures are music_art.py's, at the game's paths).

    python make_music.py "<HOI4 install folder>"

- The station box (radio_decoration, at the window's top left): the game's paper with a radio mast on it, its title in
  the dark typewriter face; now a lacquer plate (GFX_valsora_deco_music_station), the top bar's note in a well
  (GFX_valsora_deco_music_note, the music button's own icon) and the title in the gilt capitals of the other screens.
- The track list stays on its ivory sheet (the core skin's paper), the tracks in the typewriter face, dark on it.

It also writes interface/valsora_deco_music.gfx: those two sprites and the top bar controller's tab
(GFX_valsora_deco_music_tab, which make_topbar.py puts under the music button).
"""
import os
import sys

import guipatch as GP
from music_art import STATION, TAB
from paths import MOD, VANILLA as VANILLA_DIR

ARG = sys.argv[1] if len(sys.argv) > 1 else VANILLA_DIR
t = open(os.path.join(ARG, "interface", "musicplayer.gui"), encoding="utf-8-sig").read().replace("\r\n", "\n")
W = "musicplayer_window>radio_decoration"
assert GP.get_pos(t, f"{W}>radio_icon") == (58, 25), "the station box's icon moved in the game's file"
assert GP.get_pos(t, f"{W}>cake") == (15, 84), "the station box's title moved in the game's file"
t = GP.set_background(t, W, "GFX_valsora_deco_music_station")
t = GP.set_attrs(t, f"{W}>radio_icon", sprite="GFX_valsora_deco_music_note", position=STATION["note_xy"])
t = GP.set_attrs(t, f"{W}>cake", font="valsora_deco_title_18", position=(15, STATION["title_y"]))
GP.write_gui(MOD + "interface/musicplayer.gui", t)

V = "gfx/interface/valsora_deco/"
gfx = ("# Valsora Deco UI - the music player's own sprites (interface/musicplayer.gui) and the top bar's music tab.\n"
       "# Generated by make_music.py.\n\nspriteTypes = {\n"
       f'\tspriteType = {{\n\t\tname = "GFX_valsora_deco_music_station"\n\t\ttexturefile = "{V}music_station.dds"\n\t}}\n'
       f'\tspriteType = {{\n\t\tname = "GFX_valsora_deco_music_note"\n\t\ttexturefile = "{V}music_note.dds"\n\t}}\n'
       f'\tspriteType = {{\n\t\tname = "GFX_valsora_deco_music_tab"\n\t\ttexturefile = "{V}music_tab.dds"\n'
       f'\t\t# {TAB["w"]} x {TAB["h"]}\n\t}}\n'
       "}\n")
open(MOD + "interface/valsora_deco_music.gfx", "w", encoding="utf-8", newline="\n").write(gfx)
print("musicplayer.gui and valsora_deco_music.gfx written")
